/**
 * Retrieve translation for key, fallback to EN if missing in current language
 */
export const getTranslation = (lang, key, fallback = '') => {
  const selected = (lang || 'EN').toUpperCase() === 'FR' ? 'FR' : 'EN';
  const dict = translations[selected] || translations.EN;
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }
  if (translations.EN && translations.EN[key] !== undefined) {
    return translations.EN[key];
  }
  return fallback || key;
};

/**
 * Localize terminal name into the target language
 */
export const localizeTerminal = (name, lang = 'EN') => {
  if (!name) return '';
  const selected = (lang || 'EN').toUpperCase() === 'FR' ? 'FR' : 'EN';
  const match = TERMINAL_NAMES[name.trim()];
  if (match) {
    return match[selected] || match.EN;
  }
  
  // Partial replacements if exact key doesn't match
  if (selected === 'FR') {
    let result = name;
    result = result.replace(/Jack Layton Ferry Terminal/gi, 'Terminal de traversier Jack Layton');
    result = result.replace(/Jack Layton Terminal \(Mainland\)/gi, 'Terminal Jack Layton (Continent)');
    result = result.replace(/Jack Layton Terminal/gi, 'Terminal Jack Layton');
    result = result.replace(/Centre Island Terminal/gi, 'Terminal de l’Île Centre');
    result = result.replace(/Centre Island/gi, 'Île Centre');
    result = result.replace(/Hanlan's Point Terminal/gi, 'Terminal de la Pointe Hanlan');
    result = result.replace(/Hanlan's Point/gi, 'Pointe Hanlan');
    result = result.replace(/Ward's Island Terminal/gi, 'Terminal de l’Île Ward');
    result = result.replace(/Ward's Island/gi, 'Île Ward');
    return result;
  }
  return name;
};

