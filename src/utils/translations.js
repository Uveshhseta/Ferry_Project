/**
 * Localize date according to Canadian English (en-CA) or Canadian French (fr-CA)
 */
export const formatDateLocale = (dateStr, lang = 'EN', options = {}) => {
  if (!dateStr) return '';
  try {
    const dateObj = new Date(dateStr.includes('T') ? dateStr : `${dateStr}T12:00:00`);
    if (isNaN(dateObj.getTime())) return dateStr;
    const locale = (lang || 'EN').toUpperCase() === 'FR' ? 'fr-CA' : 'en-CA';
    const defaultOptions = options && Object.keys(options).length > 0
      ? options
      : { year: 'numeric', month: 'short', day: 'numeric' };
    return new Intl.DateTimeFormat(locale, defaultOptions).format(dateObj);
  } catch {
    return dateStr;
  }
};

/**
 * Format currency according to locale preserving CAD value
 */
export const formatCurrencyLocale = (amount, lang = 'EN', currency = 'CAD') => {
  const num = typeof amount === 'number' ? amount : parseFloat(amount) || 0;
  const isFr = (lang || 'EN').toUpperCase() === 'FR';
  if (isFr) {
    return `${num.toFixed(2).replace('.', ',')} $ CAD`;
  }
  return `$${num.toFixed(2)} CAD`;
};
